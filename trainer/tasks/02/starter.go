package solution

// produce запускает горутину, которая шлёт значения 1..n в возвращаемый канал.
// Потребитель может прочитать НЕ ВСЕ значения. Горутина-продьюсер не должна
// утекать: дайте ей возможность завершиться (через done-канал).
func produce(n int, done <-chan struct{}) <-chan int {
	ch := make(chan int)
	go func() {
		defer close(ch)
		for i := 1; i <= n; i++ {
			// Ваша реализация: эта наивная отправка зависнет (утечёт),
			// если потребитель перестал читать. Используйте select с done.
			ch <- i
		}
	}()
	return ch
}
