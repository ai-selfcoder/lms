//
// Политики:
//   - "FIFO" — обслуживаем в порядке прихода, суммируем |переходов|.
//   - "SSTF" — каждый раз идём к ближайшему запросу; при равном расстоянии берём
//     меньший номер цилиндра.
//   - "SCAN" — «лифт»: едем к бо́льшим цилиндрам, обслуживая по пути, на самом
//     большом запросе разворачиваемся к меньшим (до края диска не доезжаем).
//
// Возвращаем суммарную пройденную дистанцию. Для пустого requests — 0.
//
// Пример:
//   TotalSeek(53, []int{98, 183, 37, 122, 14, 124, 65, 67}, "FIFO") // → 640
//   TotalSeek(53, []int{98, 183, 37, 122, 14, 124, 65, 67}, "SSTF") // → 236
//   TotalSeek(53, []int{98, 183, 37, 122, 14, 124, 65, 67}, "SCAN") // → 299
