// TotalSeek считает суммарное перемещение головки HDD (в цилиндрах) для очереди
// запросов при заданной политике планирования.
//
// Аргументы:
//   - start    — начальный цилиндр, над которым стоит головка;
//   - requests — номера цилиндров, которые нужно обслужить;
