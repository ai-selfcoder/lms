package solution

// Record — одна запись write-ahead log (журнала упреждающей записи).
//
// Op — вид записи:
//   - "set"    — изменение значения ключа в рамках текущей транзакции;
//   - "commit" — фиксация (commit) всех set-записей, накопленных
//     с предыдущего commit; именно после неё изменения считаются устойчивыми.
//
// Key и Val имеют смысл только для записей "set"; для "commit" они игнорируются.
type Record struct {
	Op  string
	Key string
	Val int
}
